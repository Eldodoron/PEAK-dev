import json
import os

with open(r"c:\Users\wamb9\MINECRAFT\Prism\Instances\PEAK dev\.agents\explorer_1\scan_results.json", "r", encoding="utf-8") as f:
    data = json.load(f)

print(f"Total scanned: {data['total_files']}")
print(f"Total matched files: {len(data['results'])}")

# Let's inspect specific high-confidence keywords:
antigravity_files = []
prompt_files = []
autogen_files = []
banner_files = []
other_files = []

for item in data['results']:
    fpath = item['file']
    rel = item['rel_file']
    keywords_found = set(m['keyword'] for m in item['matches'])
    
    ag = [m for m in item['matches'] if 'antigravity' in m['keyword']]
    pr = [m for m in item['matches'] if 'prompt' in m['keyword']]
    ag_gen = [m for m in item['matches'] if any(k in m['keyword'] for k in ['auto-generated', 'autogenerated', 'generated by', 'fixed by'])]
    
    if ag:
        antigravity_files.append((rel, ag))
    if pr:
        prompt_files.append((rel, pr))
    if ag_gen:
        autogen_files.append((rel, ag_gen))

print("\n--- ANTIGRAVITY EXPLICIT MENTIONS ---")
for rel, matches in antigravity_files:
    print(f"\nFile: {rel}")
    for m in matches:
        print(f"  Line {m['line']}: {m['content']}")

print("\n--- PROMPT EXPLICIT MENTIONS ---")
for rel, matches in prompt_files:
    print(f"\nFile: {rel}")
    for m in matches:
        print(f"  Line {m['line']}: {m['content']}")

print("\n--- AUTO-GENERATED / FIXED BY MENTIONS ---")
for rel, matches in autogen_files:
    print(f"\nFile: {rel}")
    for m in matches:
        print(f"  Line {m['line']}: {m['content']}")
