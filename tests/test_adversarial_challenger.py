def test_no_python_files_in_minecraft():
    """Verify that zero Python files, compiled bytecode, or shebang scripts exist anywhere in minecraft/."""
    print("[TEST 2/8] Scanning entire minecraft/ directory for any remaining Python files or bytecode...")
    py_extensions = {'.py', '.pyc', '.pyo', '.pyd', '.pyw', '.pyz', '.pyi', '.ipynb'}
    violations = []

    for root, dirs, files in os.walk(MINECRAFT_DIR):
        for f in files:
            path = Path(root) / f
            rel_path = path.relative_to(MINECRAFT_DIR)
            ext = path.suffix.lower()

            if ext in py_extensions:
                violations.append((str(rel_path), f"Extension {ext}"))

            # Check binary header for pyc
            if path.stat().st_size >= 4:
                try:
                    with open(path, 'rb') as fp:
                        header = fp.read(4)
                        # Pyc magic numbers usually end with \r\n or \r\r\n
                        if header.endswith(b'\r\n') and len(header) == 4 and header[0] in [0x61, 0xa7, 0x55, 0x33, 0x0d, 0x0f]:
                            violations.append((str(rel_path), "Possible compiled python bytecode header"))
                except Exception:
                    pass

            # Check shebang on small text files
            if ext not in {'.jar', '.zip', '.png', '.ogg', '.nbt', '.schem'}:
                try:
                    with open(path, 'r', encoding='utf-8', errors='ignore') as fp:
                        first_line = fp.readline()
                        if first_line.startswith('#!') and 'python' in first_line.lower():
                            violations.append((str(rel_path), "Python shebang"))
                except Exception:
                    pass

    if violations:
        raise AssertionError(f"Found {len(violations)} Python files in minecraft/: {violations}")
    print("  -> PASSED: Exactly 0 Python files or bytecode found across all depths of minecraft/.")

