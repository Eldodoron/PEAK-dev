def clean_invisible_unicode(text: str) -> str:
    """Normalize unicode and strip zero-width characters, normalizing whitespace."""
    normalized = unicodedata.normalize('NFKD', text)
    # Zero-width / invisible characters -> strip completely
    zero_width = ['\u200b', '\u200c', '\u200d', '\ufeff', '\u2060', '\u180e', '\u200e', '\u200f']
    for ch in zero_width:
        normalized = normalized.replace(ch, '')
    # Non-standard spaces -> standard space
    space_chars = ['\u00a0', '\u2000', '\u2001', '\u2002', '\u2003', '\u2004', '\u2005', '\u2006', '\u2007', '\u2008', '\u2009', '\u200a', '\u202f', '\u205f', '\u3000']
    for ch in space_chars:
        normalized = normalized.replace(ch, ' ')
    return normalized

