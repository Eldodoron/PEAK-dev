def test_kubejs_javascript_syntax_and_ast():
    """Verify that all 64 JS files in kubejs/ parse without syntax errors and bracket balance is 100%."""
    print("[TEST 5/8] Performing deep AST syntax checks across all KubeJS JavaScript scripts...")
    js_files = list(KUBEJS_DIR.rglob("*.js"))
    if not js_files:
        raise AssertionError("No .js files found in kubejs/!")

    if len(js_files) != 64:
        print(f"    [Info] Found {len(js_files)} JS files.")

    # Node.js syntax check
    node_available = False
    try:
        res = subprocess.run(["node", "-v"], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        if res.returncode == 0:
            node_available = True
    except FileNotFoundError:
        pass

    failed_node = []
    bracket_errors = []

    for js_p in js_files:
        if node_available:
            res = subprocess.run(["node", "-c", str(js_p)], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
            if res.returncode != 0:
                failed_node.append((str(js_p.relative_to(MINECRAFT_DIR)), res.stderr.strip()))

        # Bracket & Quote Balance Check in Python
        with open(js_p, 'r', encoding='utf-8') as fp:
            src = fp.read()

        # Tokenize roughly checking brackets outside strings and comments
        in_line_comment = False
        in_block_comment = False
        in_single_quote = False
        in_double_quote = False
        in_backtick = False
        escape = False

        stack = []
        pairs = {'}': '{', ']': '[', ')': '('}

        i = 0
        n = len(src)
        while i < n:
            ch = src[i]
            nxt = src[i+1] if i + 1 < n else ''

            if in_line_comment:
                if ch == '\n':
                    in_line_comment = False
                i += 1
                continue

            if in_block_comment:
                if ch == '*' and nxt == '/':
                    in_block_comment = False
                    i += 2
                    continue
                i += 1
                continue

            if in_single_quote:
                if escape:
                    escape = False
                elif ch == '\\':
                    escape = True
                elif ch == "'":
                    in_single_quote = False
                i += 1
                continue

            if in_double_quote:
                if escape:
                    escape = False
                elif ch == '\\':
                    escape = True
                elif ch == '"':
                    in_double_quote = False
                i += 1
                continue

            if in_backtick:
                if escape:
                    escape = False
                elif ch == '\\':
                    escape = True
                elif ch == '`':
                    in_backtick = False
                i += 1
                continue

            # Check comments
            if ch == '/' and nxt == '/':
                in_line_comment = True
                i += 2
                continue
            if ch == '/' and nxt == '*':
                in_block_comment = True
                i += 2
                continue

            # Check quotes
            if ch == "'":
                in_single_quote = True
                i += 1
                continue
            if ch == '"':
                in_double_quote = True
                i += 1
                continue
            if ch == '`':
                in_backtick = True
                i += 1
                continue

            # Check brackets
            if ch in '({[':
                stack.append((ch, i))
            elif ch in ')}]':
                expected = pairs[ch]
                if not stack or stack[-1][0] != expected:
                    bracket_errors.append((str(js_p.relative_to(MINECRAFT_DIR)), f"Mismatched closing '{ch}' at char {i}"))
                    break
                stack.pop()

            i += 1

        if stack and not bracket_errors:
            unclosed = [s[0] for s in stack]
            bracket_errors.append((str(js_p.relative_to(MINECRAFT_DIR)), f"Unclosed brackets: {unclosed}"))

    if failed_node:
        raise AssertionError(f"Node.js syntax check failed on {len(failed_node)} files: {failed_node}")

    if bracket_errors:
        raise AssertionError(f"Bracket integrity check failed on {len(bracket_errors)} files: {bracket_errors}")

    print(f"  -> PASSED: All {len(js_files)} JS files parsed cleanly under Node.js and verified 100% bracket balance.")

