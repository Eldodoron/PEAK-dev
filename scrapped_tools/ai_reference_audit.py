# 4. Conversational / Inner Monologue / Brainstorming
CONVERSATIONAL_WORDS = {
    "wait", "let's", "actually", "remember", "notice", "surely", "basically",
    "essentially", "naturally", "obviously", "oops", "hmm", "hmmm", "hey",
    "huh", "anyway", "besides", "honestly", "frankly", "note to self"
}
CONVERSATIONAL_RE = re.compile(r"\b(wait\s*[,.]|let\'?s|actually\s*[,.]|note\s+to\s+self|oops|hmm+|remember\s+to|notice\s+that)\b", re.IGNORECASE)

# 5. First-Person Pronouns (in dev comments, not player quests)
FIRST_PERSON_PRONOUNS = {"we", "we're", "we've", "we'll", "our", "ours", "ourselves", "i'm", "i've", "i'll", "i'd", "my", "mine", "myself"}
STANDALONE_I_RE = re.compile(
    r"\bI\b\s+(am|was|have|had|will|would|can|could|should|might|must|think|thought|noticed|found|added|removed|fixed|created|checked|want|wanted|suggest|recommend|need|tried|know|believe|hope|see|saw)\b",
    re.IGNORECASE
)
ROMAN_NUMERAL_CONTEXT = re.compile(r"\b(tier|level|rank|phase|mark|type|stage|food|strength|resistance|regen|absorption|speed|haste|sharpness|smite|protection)\s+I\b", re.IGNORECASE)

def scan_file(filepath, is_script=False):
    matches = []
    try:
        with open(filepath, 'r', encoding='utf-8', errors='replace') as f:
            lines = f.readlines()
    except Exception as e:
        return matches

    if filepath.startswith(ROOT_DIR):
        rel_path = os.path.relpath(filepath, ROOT_DIR)
    elif filepath.startswith(DESKTOP_DIR):
        rel_path = os.path.join("DESKTOP", os.path.relpath(filepath, DESKTOP_DIR))
    else:
        rel_path = filepath

    for idx, line in enumerate(lines, 1):
        stripped = line.strip()
        if not stripped:
            continue

        target_text = stripped
        is_comment = False
        is_log = False

        if is_script:
            if '//' in line:
                target_text = line[line.index('//'):].strip()
                is_comment = True
            elif '/*' in line or line.strip().startswith('*'):
                target_text = line.strip()
                is_comment = True
            elif any(cl in line for cl in ['console.log', 'console.info', 'console.warn', 'console.error']):
                target_text = line.strip()
                is_log = True
            else:
                target_text = line.strip()

        flags = []

        # 1. AI Names
        ai_hits = AI_NAMES_RE.findall(target_text)
        if ai_hits:
            real_ai_hits = []
            for h in ai_hits:
                if h.lower() == 'antigravity' and 'irons_spellbooks:antigravity' in target_text:
                    continue
                # Also filter 'minecraft_cursor' mod name in server_pack_excluded_mods.md
                if h.lower() == 'cursor' and 'minecraft_cursor' in target_text:
                    continue
                real_ai_hits.append(h)
            if real_ai_hits:
                flags.append(("AI_NAME", list(set(real_ai_hits))))

        # 2. Buzzwords
        bw_hits = [m.group(0) for m in BUZZWORDS_RE.finditer(target_text)]
        if bw_hits:
            flags.append(("BUZZWORD", list(set(bw_hits))))

        # 3. Prompt & User meta
        prompt_hits = [m.group(0) for m in USER_PROMPT_RE.finditer(target_text)]
        if prompt_hits:
            real_prompt_hits = []
            for ph in prompt_hits:
                if 'stage 5' in ph.lower() and 'dragon' in target_text.lower():
                    real_prompt_hits.append(f"{ph} [In-game Dragon Stage]")
                elif 'phase 1' in ph.lower() or 'phase 2' in ph.lower():
                    if any(b in target_text.lower() for b in ['boss', 'vampire', 'vampillager', 'phase change']):
                        real_prompt_hits.append(f"{ph} [In-game Mob Combat Phase]")
                    else:
                        real_prompt_hits.append(ph)
                else:
                    real_prompt_hits.append(ph)
            if real_prompt_hits:
                flags.append(("PROMPT_USER", real_prompt_hits))

        # 4. Conversational / Inner monologue
        if is_comment or is_log or not is_script:
            words = [w.lower() for w in re.findall(r"\b[a-zA-Z']+\b", target_text)]
            conv_hits = [w for w in words if w in CONVERSATIONAL_WORDS]
            m_conv = CONVERSATIONAL_RE.findall(target_text)
            if m_conv:
                conv_hits.extend(m_conv)
            if conv_hits:
                filtered_conv = []
                for ch in conv_hits:
                    if ch.lower() == 'lets':
                        continue
                    filtered_conv.append(ch)
                if filtered_conv:
                    flags.append(("CONVERSATIONAL", list(set(filtered_conv))))

            # 5. First person
            fp_hits = [w for w in words if w in FIRST_PERSON_PRONOUNS]
            m_i = STANDALONE_I_RE.search(target_text)
            if m_i:
                fp_hits.append(m_i.group(0))

            cleaned_fp = []
            for w in fp_hits:
                if w == 'my' and ('my nether' in target_text.lower() or 'mynethersdelight' in target_text.lower()):
                    continue
                if w == 'mine' and ('pickaxe' in target_text.lower() or 'mine them' in target_text.lower()):
                    continue
                cleaned_fp.append(w)
            if cleaned_fp:
                flags.append(("FIRST_PERSON", list(set(cleaned_fp))))

        if flags:
            matches.append({
                "file": rel_path,
                "line": idx,
                "flags": flags,
                "text": stripped,
                "is_comment": is_comment,
                "is_log": is_log
            })

    return matches

def main():
    print("=== STARTING DEEP AI REFERENCE & BUZZWORD AUDIT ===")
    all_findings = []

    # 1. KubeJS Scripts
    print("Scanning KubeJS scripts...")
    for root, dirs, files in os.walk(KUBEJS_DIR):
        for f in sorted(files):
            if f.endswith('.js'):
                path = os.path.join(root, f)
                all_findings.extend(scan_file(path, is_script=True))

    # 2. FTB Quests
    ftb_dir = os.path.join(CONFIG_DIR, 'ftbquests')
    print("Scanning FTB Quests...")
    if os.path.exists(ftb_dir):
        for root, dirs, files in os.walk(ftb_dir):
            for f in sorted(files):
                if f.endswith(('.snbt', '.json')):
                    path = os.path.join(root, f)
                    all_findings.extend(scan_file(path, is_script=False))

    # 3. Custom Datapacks & Paxi
    print("Scanning Custom Datapacks & Paxi...")
    paxi_dp = os.path.join(CONFIG_DIR, 'paxi', 'datapacks')
    if os.path.exists(paxi_dp):
        for root, dirs, files in os.walk(paxi_dp):
            for f in sorted(files):
                if f.endswith(('.json', '.mcmeta', '.snbt', '.txt')):
                    path = os.path.join(root, f)
                    all_findings.extend(scan_file(path, is_script=False))

    root_dp = os.path.join(ROOT_DIR, 'minecraft', 'datapacks')
    if os.path.exists(root_dp):
        for root, dirs, files in os.walk(root_dp):
            for f in sorted(files):
                if f.endswith(('.json', '.mcmeta', '.snbt', '.txt')):
                    path = os.path.join(root, f)
                    all_findings.extend(scan_file(path, is_script=False))

    # 4. Modpack Documentation & Root Metadata
    print("Scanning Modpack Documentation...")
    doc_files = [
        os.path.join(ROOT_DIR, 'CHANGELOG.md'),
        os.path.join(ROOT_DIR, 'BACKLOG.md'),
        os.path.join(ROOT_DIR, 'README.md'),
        os.path.join(ROOT_DIR, 'CONSOLE_LOG_FINDINGS.md'),
        os.path.join(ROOT_DIR, 'minecraft', 'peak_lite_excluded_components.md'),
        os.path.join(ROOT_DIR, 'minecraft', 'server_pack_excluded_mods.md'),
        os.path.join(ROOT_DIR, 'scrapped_tools', 'curseforge_peak_dev_description_update.md'),
        os.path.join(ROOT_DIR, 'scrapped_tools', 'curseforge_peak_lite_description.md'),
        os.path.join(ROOT_DIR, 'scrapped_tools', 'modrinth_description.md')
    ]
    for df in doc_files:
        if os.path.exists(df):
            all_findings.extend(scan_file(df, is_script=False))

    # 5. Desktop Staging & Multimedia Text Files
    print("Scanning Desktop ServerPackStaging...")
    staging_dir = os.path.join(DESKTOP_DIR, "ServerPackStaging")
    if os.path.exists(staging_dir):
        for root, dirs, files in os.walk(staging_dir):
            for f in sorted(files):
                if f.endswith(('.js', '.json', '.toml', '.txt', '.snbt', '.md')):
                    path = os.path.join(root, f)
                    all_findings.extend(scan_file(path, is_script=f.endswith('.js')))

    print(f"\nTotal findings across modpack work: {len(all_findings)}\n")

    out_json = os.path.join(ROOT_DIR, 'scrapped_tools', 'ai_audit_findings.json')
    with open(out_json, 'w', encoding='utf-8') as f:
        json.dump(all_findings, f, indent=2, ensure_ascii=False)

    print(f"Findings saved to: {out_json}")

    categories = {}
    for item in all_findings:
        for cat, hits in item['flags']:
            categories[cat] = categories.get(cat, 0) + 1

    print("\nSummary by flag category:")
    for cat, count in sorted(categories.items()):
        print(f" - {cat}: {count}")

if __name__ == '__main__':
    main()
