def get_rel_path(filepath):
    if filepath.startswith(BASE_DIR):
        return os.path.relpath(filepath, BASE_DIR).replace('\\', '/')
    elif filepath.startswith(DESKTOP_DIR):
        return "DESKTOP/" + os.path.relpath(filepath, DESKTOP_DIR).replace('\\', '/')
    return filepath.replace('\\', '/')

def audit_file(filepath):
    rel = get_rel_path(filepath)
    is_script = filepath.endswith('.js')
    
    try:
        with open(filepath, 'r', encoding='utf-8', errors='replace') as f:
            lines = f.readlines()
    except Exception as e:
        return

    for line_no, raw_line in enumerate(lines, 1):
        line = raw_line.strip()
        if not line:
            continue

        # 1. Surgical check
        s_matches = SURGICAL_PAT.findall(line)
        if s_matches:
            surgical_findings.append({
                "file": rel,
                "line": line_no,
                "content": line,
                "matches": list(set(s_matches))
            })

        # 2. AI names check
        name_matches = AI_NAMES_PAT.findall(line)
        if name_matches:
            # Filter benign game mod IDs
            clean_names = []
            for nm in name_matches:
                low = nm.lower()
                if low == 'antigravity' and 'irons_spellbooks:antigravity' in line:
                    continue
                if low == 'cursor' and 'minecraft-cursor' in line:
                    continue
                clean_names.append(nm)
            if clean_names:
                ai_name_findings.append({
                    "file": rel,
                    "line": line_no,
                    "content": line,
                    "matches": list(set(clean_names))
                })

        # 3. Credit metadata (Rule 1)
        cr_matches = CREDIT_PAT.findall(line)
        if cr_matches:
            credit_findings.append({
                "file": rel,
                "line": line_no,
                "content": line,
                "credits": cr_matches
            })

        # 4. Meta prompt / user references
        meta_matches = META_PAT.findall(line)
        if meta_matches:
            meta_findings.append({
                "file": rel,
                "line": line_no,
                "content": line,
                "matches": list(set(meta_matches))
            })

        # 5. Inner thoughts & conversational commentary in comments
        if is_script:
            if '//' in line or line.startswith('*') or line.startswith('/*'):
                it_matches = DEV_CONVERSATIONAL_PAT.findall(line)
                if it_matches:
                    inner_thoughts_findings.append({
                        "file": rel,
                        "line": line_no,
                        "content": line,
                        "matches": list(set(it_matches))
                    })
        else:
            # For non-scripts, check if comment or text
            if line.startswith('#') or line.startswith('//'):
                it_matches = DEV_CONVERSATIONAL_PAT.findall(line)
                if it_matches:
                    inner_thoughts_findings.append({
                        "file": rel,
                        "line": line_no,
                        "content": line,
                        "matches": list(set(it_matches))
                    })

        # 6. Buzzwords
        for bw, pat in AI_BUZZWORDS.items():
            if bw == 'surgical': # Already captured
                continue
            b_matches = pat.findall(line)
            if b_matches:
                # Filter benign game contexts
                if bw == 'delve':
                    # Check if it's a dungeon delve / mining delve
                    pass
                if bw == 'synergy' and 'curios' in line.lower():
                    pass
                buzzword_findings.append({
                    "file": rel,
                    "line": line_no,
                    "buzzword": bw,
                    "content": line
                })

